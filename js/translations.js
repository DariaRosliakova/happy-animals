const languageButtons = document.querySelectorAll('[data-language]');

function changeLanguage(lang) {
  document.querySelectorAll('[data-lang]').forEach(element => {
    const key = element.dataset.lang;
    const translation = translations[lang][key];

    if (translation) {
      if (element.hasAttribute('data-html')) {
        element.innerHTML = translation;
      } else {
        element.textContent = translation;
      }
    }
  });

  document.querySelectorAll('[data-lang-alt]').forEach(element => {
    const key = element.dataset.langAlt;
    const translation = translations[lang][key];

    if (translation) {
      element.alt = translation;
    }
  });

  document.querySelectorAll('[data-lang-placeholder]').forEach(element => {
    const key = element.dataset.langPlaceholder;
    const translation = translations[lang][key];

    if (translation) {
      element.placeholder = translation;
    }
  });

  document.querySelectorAll('[data-lang-title]').forEach(element => {
    const key = element.dataset.langTitle;
    const translation = translations[lang][key];

    if (translation) {
      element.title = translation;
    }
  });

  document.querySelectorAll('[data-lang-tooltip]').forEach(element => {
    element.dataset.tooltip = translations[lang][element.dataset.langTooltip];
  });

  document.documentElement.lang = lang === 'ua' ? 'uk' : 'en';

  localStorage.setItem('language', lang);

  languageButtons.forEach(button => {
    button.classList.toggle('is-active', button.dataset.language === lang);
  });
}

languageButtons.forEach(button => {
  button.addEventListener('click', () => {
    const selectedLanguage = button.dataset.language;

    changeLanguage(selectedLanguage);
  });
});

const savedLanguage = localStorage.getItem('language') || 'ua';

changeLanguage(savedLanguage);
